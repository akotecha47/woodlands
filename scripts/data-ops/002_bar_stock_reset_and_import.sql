-- STEP 4 — Derive current_stock from the movement ledger
-- ============================================================
--
-- LEFT JOIN so every one of the 559 items gets a row, including the 26
-- with no movements (COALESCE -> 0). An item with no current_stock row
-- is INVISIBLE on Stock Levels — StockLevelsTab iterates current_stock
-- and joins stock_items, so a missing row drops the item from the screen
-- entirely rather than showing it at zero.
--
-- Deriving rather than re-listing quantities guarantees
-- current_stock.quantity = sum(stock_movements.quantity_change) per item.

INSERT INTO current_stock (stock_item_id, quantity)
SELECT si.id, COALESCE(SUM(sm.quantity_change), 0)
FROM stock_items si
LEFT JOIN stock_movements sm ON sm.stock_item_id = si.id
GROUP BY si.id;

