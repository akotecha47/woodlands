-- ============================================================
--
-- event_stock_allocations FKs to stock_items with ON DELETE RESTRICT and
-- is deliberately NOT deleted here — those rows belong to events, and
-- wiping them to clear the way for a stock import would destroy event
-- data. If any exist, stop with a clear message rather than an opaque
-- FK violation.

DO $$
DECLARE n integer;
BEGIN
  SELECT count(*) INTO n FROM event_stock_allocations;
  IF n > 0 THEN
    RAISE EXCEPTION
      'event_stock_allocations holds % row(s). stock_items cannot be deleted while these exist (FK is ON DELETE RESTRICT). Resolve the affected events before running this import.', n;
  END IF;
END $$;

